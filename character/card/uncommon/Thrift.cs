namespace Momizi.character.card.uncommon;

// 节约：0费/技能/罕见 —— 模板，待实现
// 消耗5点格挡，获得1点能量。升级：获得2点能量。
[RegisterCard(typeof(MomiziCardPool))]
public class Thrift : ModCardTemplate
{
    private const int energyCost = 0;
    private const CardType type = CardType.Skill;
    private const CardRarity rarity = CardRarity.Uncommon;
    private const TargetType targetType = TargetType.Self;
    private const bool shouldShowInCardLibrary = true;

    public override CardAssetProfile AssetProfile => new(
        PortraitPath: $"res://images/cards/uncommon/{GetType().Name}.png"
    );

    protected override bool IsPlayable => base.Owner.Creature.Block >= 5;
    protected override bool ShouldGlowGoldInternal => Owner.Creature.Block >= 5;
    protected override IEnumerable<DynamicVar> CanonicalVars => [
        new BlockVar(5m, ValueProp.Unpowered),
        new EnergyVar(1)
    ];

    public Thrift() : base(energyCost, type, rarity, targetType, shouldShowInCardLibrary) { }

    protected override async Task OnPlay(PlayerChoiceContext choiceContext, CardPlay cardPlay)
    {
        await CreatureCmd.LoseBlock(choiceContext,Owner.Creature, DynamicVars.Block.BaseValue,Owner.Creature);
        await PlayerCmd.GainEnergy(DynamicVars.Energy.IntValue, Owner);
    }

    protected override void OnUpgrade()
    {
        DynamicVars.Energy.UpgradeValueBy(1);
    }

    protected override IEnumerable<IHoverTip> AdditionalHoverTips => [];
}