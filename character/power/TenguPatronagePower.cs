namespace Momizi.character.power;

[RegisterPower]
public class TenguPatronagePower : ModPowerTemplate
{
    public override PowerType Type => PowerType.Buff;
    // 叠加类型，Single表示不可叠加
    public override PowerStackType StackType => PowerStackType.Single;

    public override PowerAssetProfile AssetProfile => new(
        IconPath: "res://images/powers/TenguPatronagePower.png",
        BigIconPath: "res://images/powers/TenguPatronagePower.png"
    );

    public override async Task AfterDamageGiven(PlayerChoiceContext choiceContext, Creature? dealer, DamageResult result, ValueProp props,
        Creature target, CardModel? cardSource)
    {
        if (dealer == null || dealer.PetOwner?.Creature != Owner || dealer.GetPowerAmount<WolfVanguard>() <= 0)
        {
            return;
        }

        await PowerCmd.Apply<Alert>(choiceContext, Owner, Amount, Owner, null);
    }
}
